package io.plady.moimyeon.core.support.error

enum class ErrorCode {
    // 공통/HTTP 계열 (3자리 = HTTP 상태 대응)
    E400,
    E500,

    // 회원 도메인 (4자리, E10xx)
    E1001, // 이미 탈퇴한 회원
    E1002, // 활성 상태의 회원이 아님
    E1003, // 이용 제한 상태의 회원이 아님
    E1004, // 이미 연결된 소셜 계정
    E1005, // 닉네임 형식 위반
    E1006, // 존재하는 회원이 아님
    E1007, // 닉네임 중복
    E1008, // 이미 작성된 프로필이 존재
    E1009, // 존재하는 프로필이 아님

    // 인증/소셜 로그인 (4자리, E11xx)
    E1101, // 소셜 계정에 이메일이 없음
    E1102, // 인증 필요(미인증) — 401
    E1103, // 접근 권한 없음(인가 실패) — 403
    E1104, // 세션이 유효하지 않음(리프레시 크리덴셜 없음/만료/종료) — 401

    // 약관 (4자리, E12xx)
    E1201, // 필수 약관 미동의

    // 참조 데이터 카탈로그 (4자리, E13xx)
    E1301, // 존재하지 않는 직무
    E1302, // 존재하지 않는 지역
    E1303, // 존재하지 않는 회사
}
