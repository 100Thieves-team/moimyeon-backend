package io.plady.moimyeon.core.support.error

enum class ErrorCode {
    // 공통/HTTP 계열 (3자리 = HTTP 상태 대응)
    E400,
    E500,

    // 회원 도메인 (4자리, E10xx)
    E1001, // 이미 탈퇴한 회원
    E1002, // 활성 상태의 회원이 아님
    E1003, // 이용 제한 상태의 회원이 아님
    E1004, // 이미 연결된 소셜 계정
    E1005, // 닉네임 형식 위반
    E1006, // 존재하는 회원이 아님
    E1007, // 닉네임 중복
    E1009, // 존재하는 프로필이 아님
    E1010, // 존재하는 이력서가 아님
    E1011, // 이력서 등록 가능 개수 초과
    E1012, // AI 요약이 완료되지 않은 이력서
    E1013, // 재시도할 수 없는 AI 요약 상태

    // 인증/소셜 로그인 (4자리, E11xx)
    E1101, // 소셜 계정에 이메일이 없음
    E1102, // 인증 필요(미인증) — 401
    E1103, // 접근 권한 없음(인가 실패) — 403
    E1104, // 세션이 유효하지 않음(리프레시 크리덴셜 없음/만료/종료) — 401

    // 약관 (4자리, E12xx)
    E1201, // 필수 약관 미동의

    // 참조 데이터 카탈로그 (4자리, E13xx)
    E1301, // 존재하지 않는 직무
    E1302, // 존재하지 않는 지역
    E1303, // 존재하지 않는 회사
    E1304, // 존재하지 않는(또는 회사 불일치·비활성) 채용 공고

    E1401, // 방 제목 형식 위반
    E1402, // 방 인원수 위반
    E1403, // 방 일정 규칙 위반
    E1404, // 방 설명 형식 위반
    E1405, // 방을 찾을 수 없음 (404)
    E1406, // 방장만 접근 가능 (수정·삭제·수락·반려·신청 목록) (403)
    E1407, // 방 시작 일정이 과거(미래 아님)
    E1408, // 참가 신청을 찾을 수 없음 (404)
    E1409, // 이미 처리된 참가 신청(대기 상태 아님) (409)
    E1410, // 모집 중이 아닌 방(수락 불가) (409)
    E1411, // 정원이 가득 차 수락 불가 (409)
    E1412, // 룸 진행 일정이 지나 참가 신청 불가 (409)
    E1413, // 이미 대기 중이거나 참여 중인 룸 (409)
    E1414, // 방장은 자신의 룸에 참가 신청 불가 (409)
    E1415, // 반려 또는 강퇴 이력으로 재신청 불가 (409)
    E1416, // 동시 대기 중인 참가 신청 상한 초과 (409)
    E1417, // 최대 모집 인원을 현재 참여 인원보다 작게 낮출 수 없음 (409)
    E1418, // 모집 중이 아닌 룸이라 수정 불가 (409)
    E1419, // 룸에 참여한 사람만 접근 가능 (참여자 명부) (403)
    E1420, // 참여자가 있어 룸을 취소할 수 없음 (409)
    E1421, // 최소 진행 인원에 미달해 확정 불가 (409)
    E1422, // 진행 일정이 지나 확정 불가 (409)
    E1423, // 확정된 룸의 인원이 최소와 같아 나갈 수 없음 (409)
    E1424, // 이미 진행·종료된 룸이라 나갈 수 없음 (409)
    E1425, // 참여 중인 룸이 3개라 신청 불가 (409). 대기 신청 상한(E1416)과 다른 축이다
    E1427, // 같은 공고·직무의 활성 룸이 3개라 생성 불가 (409)

    // 질문 카드셋 (4자리, E15xx)
    E1501, // 진행 확정 전 질문 카드셋 조회 불가 (409)
    E1502, // 질문 카드셋 조회 권한 없음 (403)
    E1503, // 조회 가능한 질문 카드셋 없음 (404)
    E1504, // 질문 준비 단계가 열리지 않음 (409)
    E1505, // 질문 작성·삭제 권한 없음 (403)
    E1506, // 질문 대상이 아님 (404)
    E1507, // 질문을 찾을 수 없음 (404)
    E1508, // 다른 작성자의 꼬리질문이 있어 원 질문 삭제 불가 (409)
    E1509, // 질문 댓글 접근 권한 없음 (403)
    E1510, // 진행 중이 아니라 질문 댓글 수정 불가 (409)
    E1511, // 질문 댓글을 찾을 수 없음 (404)
    E1512, // 질문 댓글을 조회할 수 없는 룸 상태 (409)

    // 알림 (E16xx)
    E1601, // 웹 푸시 등록 식별자 형식 위반

    // 룸 진행 (4자리, E17xx)
    E1701, // 진행을 시작할 수 없는 룸 상태 (409)
    E1702, // 진행 시작 권한 없음 (403)
    E1703, // 룸 진행 접근 권한 없음 (403)
    E1704, // 룸 진행 정보를 조회할 수 없는 상태 (409)
    E1705, // 출석 기록을 찾을 수 없음 (404)
    E1706, // 출석 대상과 확정 참여자 불일치 (400)

    // 클로징 (4자리, E18xx)
    E1801, // 클로징 제출 권한 없음 (403)
    E1802, // 클로징을 제출할 수 없는 룸 상태 (409)
    E1803, // 평가 대상 질문 집합 불일치 (400)

    // 라운드 피드백 (4자리, E19xx)
    E1901, // 같은 작성자의 최종 피드백 중복 등록 (409)
    E1902, // 라운드 피드백 접근 권한 없음 (403)
    E1903, // 라운드 피드백 작성 불가 상태 (409)
    E1904, // 라운드 피드백 조회 불가 상태 (409)
    E1905, // 최종 피드백 카드 없음 (404)

    // 유저 후기 (4자리, E20xx)
    E2001, // 완료된 룸이 아니라 후기 작성 불가 (409)
    E2002, // 작성자가 출석하지 않아 후기 작성 불가 (403)
    E2003, // 대상자가 출석하지 않아 후기 작성 불가 (400)
    E2004, // 자기 자신에게 후기 작성 불가 (400)
    E2005, // 삭제되지 않은 후기 중복 (409)
    E2006, // 수정·삭제할 활성 후기를 찾을 수 없음 (404)
    E2007, // 후기 작성자가 아니라 수정·삭제 불가 (403)
    E2008, // 공개 기준 시각이 지나 후기 수정·삭제 불가 (409)
}
