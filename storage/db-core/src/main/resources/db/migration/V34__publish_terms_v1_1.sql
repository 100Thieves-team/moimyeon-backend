2. 이력서를 등록하면 원본 파일을 보관하고 AI 요약을 생성합니다. 일부 개인정보를 가리는 처리를 하지만 이름·학교·회사·경력 등 개인을 알아볼 수 있는 정보가 남을 수 있습니다. 구체적인 처리 내용은 개인정보 처리방침에서 안내합니다.
3. AI 요약은 면접 준비를 돕는 참고자료입니다. 정보가 누락되거나 잘못 표현될 수 있으며, 회원은 오류를 운영자에게 알릴 수 있습니다.
