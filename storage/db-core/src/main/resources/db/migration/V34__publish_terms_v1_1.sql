8. 보관함에서 이력서를 삭제해도 이미 모임에 제출한 정보나 파일 원본이 즉시 모두 삭제되는 것은 아닙니다. 전체 삭제나 공유 중단 요청은 별도로 접수할 수 있습니다. 운영자는 다른 회원이 이미 내려받은 사본까지 원격으로 회수할 수 있다고 보장하지 않으며, 무단 이용 신고에 필요한 조치를 취합니다.

