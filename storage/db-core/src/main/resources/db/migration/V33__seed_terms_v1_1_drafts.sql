## 5. 개인정보의 국외 이전

현재 구성에서는 AWS 서울 저장·추론 경로와 Google FCM·Gmail 경로를 구분합니다. AWS 서울 구성만으로 서비스 전체가 국내에서만 처리된다고 설명하지 않습니다. 새 국외 이전 여부를 선택하는 것이 아니라 현재 사용 중인 경로의 사실을 공개하는 항목입니다.

